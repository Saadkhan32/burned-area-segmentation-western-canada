#!/usr/bin/env python3
"""Aggregate the per-window results of all runs (every window is a test window in exactly one fold).
Follows 05_protocol/evaluation_protocol_R1.md: primary statistic = mean per-window burned-class F1; window-level
bootstrap (2,000 replicates, percentile 95 % intervals, seed 42); paired comparisons by exact / Monte-Carlo sign-flip tests
on per-window differences with Holm correction over the planned pairs; hectare errors; per-province breakdown.
Usage: python summarize.py --results results --out results/summary
"""
import os, glob, csv, argparse, itertools, math
import numpy as np, pandas as pd


def boot_ci(v, n=2000, seed=42):
    v = np.asarray(v, float); v = v[~np.isnan(v)]
    if len(v) == 0: return (np.nan, np.nan)
    rng = np.random.default_rng(seed); m = [rng.choice(v, len(v)).mean() for _ in range(n)]
    return (float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5)))


def sign_flip_p(d, n_mc=20000, seed=42):
    d = np.asarray(d, float); d = d[~np.isnan(d)]; n = len(d)
    if n == 0: return np.nan
    obs = abs(d.mean())
    if n <= 20:
        signs = np.array(list(itertools.product([1, -1], repeat=n)))
        return float((np.abs((signs * d).mean(1)) >= obs - 1e-12).mean())
    rng = np.random.default_rng(seed)
    s = rng.choice([1, -1], (n_mc, n)); return float((np.abs((s * d).mean(1)) >= obs - 1e-12).mean())


def holm(pvals):
    idx = np.argsort(pvals); m = len(pvals); adj = np.empty(m); run = 0
    for rank, i in enumerate(idx):
        run = max(run, (m - rank) * pvals[i]); adj[i] = min(1.0, run)
    return adj


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--results', default='results'); ap.add_argument('--out', default='results/summary')
    ap.add_argument('--pairs', default='', help='planned comparisons, e.g. "unet:deeplabv3,unet:pspnet"; default: every model vs NBR<0 and all model pairs')
    a = ap.parse_args(); os.makedirs(a.out, exist_ok=True)
    files = sorted(glob.glob(os.path.join(a.results, '*_test_windows.csv')))
    if not files: raise SystemExit('no *_test_windows.csv in ' + a.results)
    df = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    df = df.drop_duplicates(subset=['model', 'window_id'], keep='last')   # index rules appear once per run; keep one copy
    df['is_negative'] = df.ref_ha <= 0
    neg = df[df.is_negative]; df = df[~df.is_negative]
    if len(neg):
        negs = neg.groupby('model').agg(n_negative_windows=('window_id', 'count'), mean_false_burned_ha=('pred_ha', 'mean'), max_false_burned_ha=('pred_ha', 'max'),
                                        mean_false_burned_fraction=('fp', lambda x: float((x / neg.loc[x.index, 'valid_px']).mean()))).reset_index()
        negs.to_csv(os.path.join(a.out, 'negative_windows_by_model.csv'), index=False); print(negs.round(3).to_string(index=False))
    df['abs_ha_err'] = (df.pred_ha - df.ref_ha).abs(); df['rel_ha_err'] = (df.pred_ha - df.ref_ha) / df.ref_ha.replace(0, np.nan)
    rows = []
    for model, g in df.groupby('model'):
        lo, hi = boot_ci(g.F1); pooled = 2 * g.tp.sum() / (2 * g.tp.sum() + g.fp.sum() + g.fn.sum())
        r = dict(model=model, n_windows=len(g), mean_F1=g.F1.mean(), F1_ci_lo=lo, F1_ci_hi=hi, median_F1=g.F1.median(), pooled_F1=pooled,
                 mean_P=g.P.mean(), mean_R=g.R.mean(), mean_IoU=g.IoU.mean(), median_abs_ha_err=g.abs_ha_err.median(), median_rel_ha_err=g.rel_ha_err.median())
        for pv, gg in g.groupby('province'): r[f'mean_F1_{pv}'] = gg.F1.mean()
        rows.append(r)
    summ = pd.DataFrame(rows).sort_values('mean_F1', ascending=False); summ.to_csv(os.path.join(a.out, 'summary_by_model.csv'), index=False)
    models = [m for m in summ.model if m not in ('NBR<0', 'Otsu(NBR)')]
    if a.pairs:
        pairs = [tuple(p.split(':')) for p in a.pairs.split(',')]
    else:
        pairs = [(m, 'NBR<0') for m in models] + list(itertools.combinations(models, 2))
    wide = df.pivot(index='window_id', columns='model', values='F1')
    prow = []
    for x, y in pairs:
        if x not in wide or y not in wide: continue
        d = (wide[x] - wide[y]).dropna(); lo, hi = boot_ci(d)
        prow.append(dict(model_a=x, model_b=y, n=len(d), mean_diff_F1=d.mean(), diff_ci_lo=lo, diff_ci_hi=hi, wins_a=int((d > 0).sum()), p_signflip=sign_flip_p(d)))
    if prow:
        pr = pd.DataFrame(prow); pr['p_holm'] = holm(pr.p_signflip.values); pr.to_csv(os.path.join(a.out, 'paired_differences.csv'), index=False)
    df.to_csv(os.path.join(a.out, 'all_windows.csv'), index=False)
    with open(os.path.join(a.out, 'summary.md'), 'w') as f:
        f.write('# Results summary (generated by summarize.py)\n\nMean per-window burned-class F1 with window-bootstrap 95 % intervals; every window scored once in the fold that held out its province.\n\n')
        f.write(summ.round(3).to_markdown(index=False) + '\n\n')
        if prow: f.write('## Paired differences (per-window F1, sign-flip test, Holm-adjusted)\n\n' + pr.round(4).to_markdown(index=False) + '\n')
        if len(neg): f.write('\n## Negative windows (no burn in the reference): falsely mapped burned area\n\n' + negs.round(3).to_markdown(index=False) + '\n')
    print(summ.round(3).to_string(index=False))
    if prow: print(pr.round(4).to_string(index=False))


if __name__ == '__main__':
    main()
